#!/usr/bin/env bash
# Regenerates the embedded mp-darkmode script from Support/ThirdParty/mp-darkmode.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
source_dir="$root/Support/ThirdParty/mp-darkmode"
output="$root/Sources/PlainpostUI/Vendor/MPDarkmodeScript.swift"
if grep -q '"####' "$source_dir/darkmode.min.js"; then
  echo "darkmode.min.js contains the raw-string delimiter; choose another." >&2
  exit 1
fi
{
  echo "// Generated by Scripts/vendor-mp-darkmode.sh from Support/ThirdParty/mp-darkmode. Do not edit."
  echo "//"
  sed 's|^|// |' "$source_dir/LICENSE"
  echo
  echo "/// mp-darkmode (WeChat's rich-text dark-mode conversion), run in the mail reader."
  echo "enum MPDarkmodeScript {"
  printf '    static let source = ####"""\n'
  cat "$source_dir/darkmode.min.js"
  printf '\n"""####\n'
  echo "}"
} > "$output"
echo "Wrote $output"
